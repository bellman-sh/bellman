/**
 * The docs site's tool reference, rendered: a page per server tool, and one page for the tools a
 * hook-mode bridge adds to the server's. scripts/docs-gen.ts writes this render and
 * tests/docs-reference.test.ts compares the committed pages with it byte for byte, so the script and
 * the drift test cannot read the tools two ways. Nothing runs at import: the test imports this file.
 *
 * The tools are the ones tests/helpers/tool-lists.ts lists, as a client lists them, so a page shows
 * what an agent is shown: the title, the description, the input schema and the annotations.
 */
import { fileURLToPath } from "node:url";
import type { Tool } from "@modelcontextprotocol/sdk/types.js";
import { listHookBridgeTools, listServerTools } from "../tests/helpers/tool-lists.js";

/** Absolute path of docs-site/src/content/docs/, so the script and the test agree from any working directory. */
export const CONTENT_DIR = fileURLToPath(new URL("../docs-site/src/content/docs/", import.meta.url));
/** Where the server tools' pages live, under CONTENT_DIR. */
export const TOOLS_DIR = "reference/tools";
/** The one page for the tools a hook-mode bridge adds, under CONTENT_DIR. */
export const BRIDGE_PAGE = "reference/bridge-tools.md";

/** The part of JSON Schema a tool's input uses. */
export interface JsonSchema {
  type?: string | string[];
  anyOf?: JsonSchema[];
  items?: JsonSchema;
  enum?: unknown[];
  default?: unknown;
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
}

const BANNER =
  "<!-- Generated by npm run docs:gen from each tool's own definition: edit the tool in src/, then run it again. -->";

const BRIDGE_INTRO =
  "The local bridge runs on your machine. The Claude Code plugin, the npm package's `bellman-channel` " +
  "and the Claude Desktop bundle each start one. It lists every server tool and adds the tools below. " +
  "`bellman_wait` is listed only when the bridge runs in hook delivery, as the plugin and the bundle do.";

/** What a table cell says when it has nothing to say. */
const NONE = "\u{2014}";

/**
 * Tool text becomes Markdown, where a `<` can open a tag and an `&` an entity. Both are escaped, `&`
 * first so the `&` in `&lt;` is not escaped again. A code span is left as written: inside one an
 * entity is shown literally, so `&lt;` there would reach the reader as those four characters.
 */
export function escapeProse(text: string): string {
  return text
    .split(/(`[^`\n]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/&/g, "&amp;").replace(/</g, "&lt;")))
    .join("");
}

/** Reads, Writes or Destructive, from MCP's annotations: a hint left out is false for readOnlyHint and true for destructiveHint. */
export function labelOf(annotations: Tool["annotations"]): "Reads" | "Writes" | "Destructive" {
  if (annotations?.readOnlyHint === true) return "Reads";
  return annotations?.destructiveHint === false ? "Writes" : "Destructive";
}

/** A parameter's type as a reader says it: `string[]`, `string or null`, `any` for a schema that names none. */
export function typeOf(schema: JsonSchema): string {
  if (schema.anyOf) return [...new Set(schema.anyOf.map(typeOf))].join(" or ");
  if (Array.isArray(schema.type)) return schema.type.join(" or ");
  if (schema.type === "array") return `${schema.items ? typeOf(schema.items) : "any"}[]`;
  return schema.type ?? "any";
}

function titleOf(tool: Tool): string {
  const title = tool.title ?? tool.annotations?.title;
  if (!title) throw new Error(`${tool.name} has no title`);
  return title;
}

/**
 * Two trailing spaces end a Markdown line without ending its paragraph, so a description keeps its lines.
 * An unindented line straight after an indented list gets a blank line first, or Markdown reads it as part
 * of the list's last bullet.
 */
function keepLines(text: string): string[] {
  const lines = escapeProse(text).split("\n");
  const afterList = (i: number) => /^\s+\S/.test(lines[i - 1] ?? "") && !/^\s/.test(lines[i]);
  return lines.flatMap((line, i) => {
    if (!line.trim()) return [""];
    const kept = line.trimEnd() + "  ";
    return afterList(i) ? ["", kept] : [kept];
  });
}

/** One row per parameter, depth first in listed order, a nested object's own parameters after it as `parent.child`. */
function rowsOf(schema: JsonSchema, prefix = ""): string[][] {
  const required = new Set(schema.required);
  return Object.entries(schema.properties ?? {}).flatMap(([name, prop]) => [
    [
      `\`${prefix}${name}\``,
      typeOf(prop),
      required.has(name) ? "yes" : "no",
      escapeProse(prop.description ?? "").replace(/\n/g, " "),
      (prop.enum ?? prop.items?.enum ?? []).map((value) => `\`${String(value)}\``).join(", "),
      prop.default === undefined ? "" : `\`${JSON.stringify(prop.default)}\``,
    ],
    ...rowsOf(prop, `${prefix}${name}.`),
  ]);
}

function parameters(tool: Tool): string[] {
  const rows = rowsOf(tool.inputSchema as JsonSchema);
  if (rows.length === 0) return ["This tool takes no parameters."];
  return [
    "| Name | Type | Required | Description | Values | Default |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows.map((cells) => `| ${cells.map((cell) => (cell || NONE).replace(/\|/g, "\\|")).join(" | ")} |`),
  ];
}

/** A tool's page from its label down: what a tool page and a section of the bridge page share. */
function body(tool: Tool, heading: string): string[] {
  return [
    `**${labelOf(tool.annotations)}**`,
    "",
    ...keepLines(tool.description ?? ""),
    "",
    `${heading} Parameters`,
    "",
    ...parameters(tool),
  ];
}

export function toolPage(tool: Tool): string {
  return [
    "---",
    `title: ${JSON.stringify(tool.name)}`,
    `description: ${JSON.stringify(titleOf(tool))}`,
    "---",
    "",
    BANNER,
    "",
    ...body(tool, "##"),
    "",
  ].join("\n");
}

export function bridgePage(tools: Tool[]): string {
  return [
    "---",
    'title: "Bridge tools"',
    `description: ${JSON.stringify("The tools the local bridge adds to the server's.")}`,
    "---",
    "",
    BANNER,
    "",
    BRIDGE_INTRO,
    "",
    ...tools.flatMap((tool) => [
      `## ${tool.name}`,
      "",
      `*${escapeProse(titleOf(tool))}*`,
      "",
      ...body(tool, "###"),
      "",
    ]),
  ].join("\n");
}

/** Every page, keyed by its path under CONTENT_DIR: a page per server tool in listed order, then the bridge's. */
export async function referencePages(): Promise<Map<string, string>> {
  const server = await listServerTools();
  const serverNames = new Set(server.map((tool) => tool.name));
  const pages = new Map<string, string>();
  for (const tool of server) pages.set(`${TOOLS_DIR}/${tool.name}.md`, toolPage(tool));
  const bridgeOwn = (await listHookBridgeTools()).filter((tool) => !serverNames.has(tool.name));
  pages.set(BRIDGE_PAGE, bridgePage(bridgeOwn));
  return pages;
}
