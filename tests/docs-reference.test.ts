/**
 * The generated reference on docs.bellman.sh (docs site spec, "The generated reference"): a page per
 * server tool and one for the bridge's own, rendered from the tools as a client lists them.
 * scripts/docs-gen.ts writes this same render, so the drift test is byte-exact: change a tool's title,
 * description, schema or annotations without `npm run docs:gen`, and it fails.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import type { Tool } from "@modelcontextprotocol/sdk/types.js";
import {
  BRIDGE_PAGE, CONTENT_DIR, TOOLS_DIR, bridgePage, escapeProse, labelOf, referencePages, toolPage, typeOf,
} from "../scripts/docs-reference.js";
import { listServerTools } from "./helpers/tool-lists.js";

const fixture: Tool = {
  name: "bellman_example",
  title: 'Try the "example": a fixture',
  description: "Do one thing <safely> & well.\n\nArgs:\n  - mode: `<mode>` picks it\n    and this line continues it\nErrors: it can fail\nor it can hang",
  inputSchema: {
    type: "object",
    properties: {
      mode: { type: "string", enum: ["fast", "slow"], default: "fast", description: "How | quickly\nit runs" },
      brief: {
        type: "object",
        description: "What you know",
        properties: {
          goal: { type: "string", description: "One <line>" },
          notes: { type: "array", items: { type: "string" }, default: [] },
        },
        required: ["goal"],
      },
    },
    required: ["brief"],
  },
  annotations: { readOnlyHint: false, destructiveHint: false },
};

describe("escaping tool text", () => {
  it("escapes & and then <, so <your key> renders as written", () => {
    expect(escapeProse("Bearer <your key> & co")).toBe("Bearer &lt;your key> &amp; co");
    expect(escapeProse("&lt;")).toBe("&amp;lt;");
  });

  // Review Focus 5: inside a code span an entity is shown literally, so a code span keeps its text.
  it("leaves a code span as written", () => {
    expect(escapeProse("`<name>` and <name> & `a&b`")).toBe("`<name>` and &lt;name> &amp; `a&b`");
  });

  it("shows bellman_start's <role> as text, not as a tag", async () => {
    const page = (await referencePages()).get(`${TOOLS_DIR}/bellman_start.md`)!;
    expect(page).toContain("&lt;role>");
    expect(page).not.toContain("<role>");
  });
});

describe("a tool's label", () => {
  it("comes from readOnlyHint, then destructiveHint, with MCP's defaults for a hint left out", () => {
    expect([
      labelOf({ readOnlyHint: true }),
      labelOf({ readOnlyHint: true, destructiveHint: true }),
      labelOf({ readOnlyHint: false, destructiveHint: false }),
      labelOf({ readOnlyHint: false, destructiveHint: true }),
      labelOf({ readOnlyHint: false }),
      labelOf(undefined),
    ]).toEqual(["Reads", "Reads", "Writes", "Destructive", "Destructive", "Destructive"]);
  });

  it("labels the real tools by their own annotations", async () => {
    const pages = await referencePages();
    const label = (name: string) =>
      pages.get(`${TOOLS_DIR}/${name}.md`)?.match(/^\*\*(Reads|Writes|Destructive)\*\*$/m)?.[1];
    expect({ sync: label("bellman_sync"), send: label("bellman_send"), evict: label("bellman_evict") })
      .toEqual({ sync: "Reads", send: "Writes", evict: "Destructive" });
  });
});

describe("a parameter's type", () => {
  it("reads a type, an array's items, a list of types and a union", () => {
    expect([
      typeOf({ type: "string" }),
      typeOf({ type: "array", items: { type: "string", enum: ["a"] } }),
      typeOf({ type: "array" }),
      typeOf({ type: ["boolean", "null"] }),
      typeOf({ anyOf: [{ type: "object" }, { type: "object" }] }),
      typeOf({ anyOf: [{ type: "string" }, { type: "null" }] }),
      typeOf({}),
    ]).toEqual(["string", "string[]", "any[]", "boolean or null", "object", "string or null", "any"]);
  });
});

describe("a tool page", () => {
  // Review Focus 2 and 4: the description keeps its lines, and a pipe or newline in a cell keeps its row.
  // An unindented line straight after an indented list starts a paragraph of its own: without the blank
  // line before "Errors:", Markdown reads it as part of the last bullet. "or it can hang" follows an
  // unindented line, so it stays in that paragraph.
  it("is frontmatter, the label, the description with its lines kept, and a parameters table", () => {
    expect(toolPage(fixture)).toBe([
      "---",
      'title: "bellman_example"',
      'description: "Try the \\"example\\": a fixture"',
      "---",
      "",
      "<!-- Generated by npm run docs:gen from each tool's own definition: edit the tool in src/, then run it again. -->",
      "",
      "**Writes**",
      "",
      "Do one thing &lt;safely> &amp; well.  ",
      "",
      "Args:  ",
      "  - mode: `<mode>` picks it  ",
      "    and this line continues it  ",
      "",
      "Errors: it can fail  ",
      "or it can hang  ",
      "",
      "## Parameters",
      "",
      "| Name | Type | Required | Description | Values | Default |",
      "| --- | --- | --- | --- | --- | --- |",
      '| `mode` | string | no | How \\| quickly it runs | `fast`, `slow` | `"fast"` |',
      "| `brief` | object | yes | What you know | \u{2014} | \u{2014} |",
      "| `brief.goal` | string | yes | One &lt;line> | \u{2014} | \u{2014} |",
      "| `brief.notes` | string[] | no | \u{2014} | \u{2014} | `[]` |",
      "",
    ].join("\n"));
  });

  it("says so when a tool takes no parameters", () => {
    expect(toolPage({ ...fixture, inputSchema: { type: "object", properties: {} } }))
      .toContain("## Parameters\n\nThis tool takes no parameters.\n");
  });

  it("takes its description from the tool's title, then its annotations' title, and refuses a tool with neither", () => {
    expect(toolPage({ ...fixture, title: undefined, annotations: { title: "From the annotation" } }))
      .toContain('description: "From the annotation"');
    expect(() => toolPage({ ...fixture, title: undefined, annotations: {} })).toThrow("bellman_example has no title");
  });
});

describe("the bridge tools page", () => {
  it("heads each tool with its name and title, and puts its parameters one level down", () => {
    const page = bridgePage([fixture]);
    expect(page.startsWith('---\ntitle: "Bridge tools"\n')).toBe(true);
    expect(page).toContain('## bellman_example\n\n*Try the "example": a fixture*\n\n**Writes**\n\n');
    expect(page).toContain("### Parameters\n\n| Name |");
  });
});

describe("the reference", () => {
  it("is a page per server tool, and one page for the tools a hook-mode bridge adds", async () => {
    const pages = await referencePages();
    const server = (await listServerTools()).map((t) => t.name).sort();
    const toolPages = [...pages.keys()]
      .filter((path) => path.startsWith(`${TOOLS_DIR}/`))
      .map((path) => path.slice(TOOLS_DIR.length + 1, -".md".length))
      .sort();
    const bridgeTools = [...pages.get(BRIDGE_PAGE)!.matchAll(/^## (\S+)$/gm)].map((m) => m[1]);
    expect({ toolPages, bridgeTools, size: pages.size }).toEqual({
      toolPages: server,
      bridgeTools: ["bellman_wait", "bellman_whoami", "bellman_upload"],
      size: server.length + 1,
    });
  });

  // Review Focus 3: a removed or renamed tool leaves an orphan, which fails here until docs:gen deletes it.
  it("is committed as npm run docs:gen writes it", async () => {
    const pages = await referencePages();
    const stale = [...pages]
      .filter(([path, text]) => {
        const file = join(CONTENT_DIR, path);
        return !existsSync(file) || readFileSync(file, "utf8") !== text;
      })
      .map(([path]) => path);
    const dir = join(CONTENT_DIR, TOOLS_DIR);
    const orphans = (existsSync(dir) ? readdirSync(dir) : [])
      .filter((name) => name.endsWith(".md"))
      .map((name) => `${TOOLS_DIR}/${name}`)
      .filter((path) => !pages.has(path));
    expect({ stale, orphans }, "run npm run docs:gen").toEqual({ stale: [], orphans: [] });
  });
});
